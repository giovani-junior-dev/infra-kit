// Identidade do alvo = (nome, env): o mesmo projeto existe como nome@hml e nome@prod.
// Precisa de DOIS servidores Postgres de verdade (mesmo nome de banco e de roles nos dois):
//   DB_MCP_IT_ADMIN_URL      superuser descartável ("servidor prod")
//   DB_MCP_IT_HML_ADMIN_URL  superuser de OUTRA instância ("servidor hml")
//   DB_MCP_IT_PG_BIN_DIR     pasta com pg_dump/pg_restore 16 (senão usa o PATH)
// A parte da migration 003 só precisa de DB_MCP_IT_ADMIN_URL.
import { randomBytes } from 'node:crypto'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import pg from 'pg'
import { createRuntime, type Runtime } from '../src/runtime'
import { handleApproval, signToken } from '../src/approval/link'
import { createHandlers } from '../src/tools/handlers'
import { parseKey } from '../src/crypto'
import type { Agent } from '../src/types'
import { createControlDb } from './fixtures/control-db'

const ADMIN = process.env.DB_MCP_IT_ADMIN_URL
const HML_ADMIN = process.env.DB_MCP_IT_HML_ADMIN_URL
const SECRET = 'it-secret'
const CONTROL = 'dbmcp_tenv_control'
const ROLES = ['dbmcp_tenv_admin', 'mcp_teste_rw', 'mcp_teste_exec', 'mcp_teste_ddl']

const withDb = (url: string, db: string, user?: string, pass?: string) => {
  const u = new URL(url)
  u.pathname = `/${db}`
  if (user) { u.username = user; u.password = pass ?? '' }
  return u.toString()
}

async function run(url: string, sql: string, params: unknown[] = []) {
  const c = new pg.Client({ connectionString: url })
  await c.connect()
  try { return await c.query(sql, params) } finally { await c.end() }
}

async function reset(url: string) {
  for (const d of ['teste', CONTROL, 'dbmcp_tenv_old']) await run(url, `DROP DATABASE IF EXISTS ${d} WITH (FORCE)`)
  for (const r of ROLES) await run(url, `DROP ROLE IF EXISTS ${r}`)
}

describe.skipIf(!ADMIN || !HML_ADMIN)('db-mcp alvos nome@env em dois servidores', () => {
  let rt: Runtime
  const agent: Agent = { clientId: 'cid', name: 'agente-it', targets: ['teste@hml', 'teste@prod'], active: true }
  const h = () => createHandlers(rt.toolContext(agent))
  const opId = (r: unknown) => (r as { opId: string }).opId

  async function approve(id: string) {
    const op = (await rt.store.getOp(id))!
    await handleApproval(rt.approval, { id: op.id, token: signToken(op.id, op.expiresAt, SECRET), action: 'approve', by: 'dono', now: new Date() })
    return rt.store.getOp(id)
  }
  const rows = async (ref: string, sql: string) => (await run(rt.targets.get(ref)!.dsnDdl, sql)).rows

  beforeAll(async () => {
    for (const url of [ADMIN!, HML_ADMIN!]) {
      await reset(url)
      await run(url, `CREATE ROLE dbmcp_tenv_admin LOGIN PASSWORD 'pw' CREATEDB CREATEROLE`)
    }
    const controlDsn = await createControlDb(ADMIN!, CONTROL)
    await run(controlDsn, "INSERT INTO agents (client_id, name, targets) VALUES ('cid', 'agente-it', '{}')")
    rt = await createRuntime({
      targets: new Map(),
      controlDsn,
      secret: SECRET,
      baseUrl: 'http://127.0.0.1:8002',
      adminDsns: { hml: withDb(HML_ADMIN!, 'postgres', 'dbmcp_tenv_admin', 'pw'), prod: withDb(ADMIN!, 'postgres', 'dbmcp_tenv_admin', 'pw') },
      targetsKey: parseKey(randomBytes(32).toString('hex')),
      pgBinDir: process.env.DB_MCP_IT_PG_BIN_DIR,
      env: {},
    })
  }, 60_000)

  afterAll(async () => {
    await rt?.close()
    for (const url of [ADMIN, HML_ADMIN]) if (url) await reset(url)
  })

  it('cria teste@hml e prepara o projeto', async () => {
    expect(await approve(opId(await h().db_create_database({ name: 'teste', env: 'hml', reason: 'it' })))).toMatchObject({ status: 'executed' })
    expect(rt.targets.get('teste@hml')).toMatchObject({ name: 'teste', env: 'hml' })
    // O agente que pediu já sai com o alvo liberado: sem passo manual de grant.
    expect((await rt.store.getAgent('cid'))?.targets).toEqual(['teste@hml'])
    for (const sql of [
      'CREATE TABLE produtos (id int PRIMARY KEY, nome text NOT NULL)',
      'CREATE TABLE clientes (id int PRIMARY KEY, nome text)',
      'CREATE TABLE itens (id serial PRIMARY KEY, nome text)',
      'CREATE TABLE pedidos (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, nome text)',
      'CREATE TABLE notas (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome text)',
    ]) {
      expect(await h().db_ddl({ target: 'teste@hml', sql, reason: 'it' })).toMatchObject({ status: 'executed' })
    }
    await h().db_insert({ target: 'teste', sql: "INSERT INTO produtos VALUES (1, 'caneta'), (2, 'lápis')", reason: 'it' })
    await h().db_insert({ target: 'teste@hml', sql: "INSERT INTO clientes VALUES (1, 'teste hml')", reason: 'it' })
    const hml = rt.targets.get('teste@hml')!.dsnRw
    await run(hml, "INSERT INTO itens VALUES (1, 'a'), (5, 'b')")
    await run(hml, "INSERT INTO pedidos (nome) VALUES ('p1'), ('p2'), ('p3')")
  })

  it('promote teste@hml → teste@prod cria o banco no admin prod, copia dados e diff zero', async () => {
    const r = await h().db_promote_project({ from: 'teste@hml', copy_tables: ['produtos', 'itens', 'pedidos', 'notas'], reason: 'go-live' })
    expect(r).toMatchObject({ status: 'pending', estimatedRows: 5 })
    expect(await approve(opId(r))).toMatchObject({
      status: 'executed',
      result: { created: true, migrations: 5, copied: { produtos: 2, itens: 2, pedidos: 3, notas: 0 }, diff: { onlyHml: [], onlyProd: [] } },
    })
    const prod = rt.targets.get('teste@prod')!
    expect(prod).toMatchObject({ name: 'teste', env: 'prod' })
    expect(new URL(prod.dsnDdl).port).toBe(new URL(ADMIN!).port)
    expect(new URL(rt.targets.get('teste@hml')!.dsnDdl).port).toBe(new URL(HML_ADMIN!).port)
    expect(await rows('teste@prod', 'SELECT id, nome FROM produtos ORDER BY id')).toEqual([{ id: 1, nome: 'caneta' }, { id: 2, nome: 'lápis' }])
    expect(await rows('teste@prod', 'SELECT count(*)::int AS n FROM clientes')).toEqual([{ n: 0 }])
    const saved = (await run(withDb(ADMIN!, CONTROL), 'SELECT name, env FROM targets ORDER BY env')).rows
    expect(saved).toEqual([{ name: 'teste', env: 'hml' }, { name: 'teste', env: 'prod' }])
    expect((await rt.store.getAgent('cid'))?.targets).toEqual(['teste@hml', 'teste@prod'])
  })

  it('depois do promote, INSERT em prod pega max(id)+1 (serial e identity); tabela vazia começa em 1', async () => {
    const exec = rt.targets.get('teste@prod')!.dsnExec
    const next = async (t: string) => (await run(exec, `INSERT INTO ${t} (nome) VALUES ('novo') RETURNING id`)).rows[0].id
    expect(await next('itens')).toBe(6)
    expect(await next('pedidos')).toBe(4)
    expect(Number(await next('notas'))).toBe(1)
  })

  it('nome sem @ existente nos dois envs: erro claro, nada escrito', async () => {
    await expect(h().db_insert({ target: 'teste', sql: "INSERT INTO produtos VALUES (9, 'x')", reason: 'it' })).rejects.toThrow(/ambíguo.*teste@hml.*teste@prod/)
    await expect(h().db_promote_project({ from: 'teste', reason: 'x' })).rejects.toThrow(/@hml ou .*@prod/)
    expect(await rows('teste@hml', 'SELECT count(*)::int AS n FROM produtos WHERE id = 9')).toEqual([{ n: 0 }])
    expect(await rows('teste@prod', 'SELECT count(*)::int AS n FROM produtos WHERE id = 9')).toEqual([{ n: 0 }])
  })

  it('segunda promoção só aplica a migration nova', async () => {
    await h().db_ddl({ target: 'teste@hml', sql: 'ALTER TABLE produtos ADD COLUMN preco int', reason: 'it' })
    const r = await h().db_promote_project({ from: 'teste@hml', database: 'teste', reason: 'release 2' })
    expect(r).toMatchObject({ estimatedRows: 1 })
    expect(await approve(opId(r))).toMatchObject({
      status: 'executed', result: { created: false, migrations: 1, copied: {}, diff: { onlyHml: [], onlyProd: [] } },
    })
    expect((await h().db_migrations_export({ target: 'teste@prod' })).count).toBe(6)
  })

  it('mirror teste@prod → teste@hml (destino default)', async () => {
    await run(rt.targets.get('teste@prod')!.dsnExec, "INSERT INTO clientes VALUES (7, 'Cliente Prod')")
    const op = await approve(opId(await h().db_mirror_to_homolog({ from: 'teste@prod', reason: 'refresh' })))
    expect(op).toMatchObject({ status: 'executed', result: { from: 'teste@prod', to: 'teste@hml' } })
    expect(await rows('teste@hml', 'SELECT id, nome FROM clientes')).toEqual([{ id: 7, nome: 'Cliente Prod' }])
    expect((await rt.store.listUnapplied('teste@hml')).length).toBe(0)
    const sums = async (ref: string) => (await rt.store.listMigrations(ref)).map((m) => m.checksum)
    expect(await sums('teste@hml')).toEqual(await sums('teste@prod'))
  })

  it('mirror com falha no registro de controle: failed deixa claro que o hml já foi recriado', async () => {
    await run(withDb(ADMIN!, CONTROL), 'REVOKE DELETE ON migrations FROM mcp_control_rw')
    try {
      await h().db_ddl({ target: 'teste@hml', sql: 'CREATE TABLE so_hml (id int)', reason: 'it' })
      const op = await approve(opId(await h().db_mirror_to_homolog({ from: 'teste@prod', reason: 'refresh' })))
      expect(op).toMatchObject({ status: 'failed', result: { step: 'control', hmlRecreated: true, from: 'teste@prod', to: 'teste@hml' } })
      expect(JSON.stringify(op?.result)).toMatch(/permission denied for table migrations/)
      expect(await rows('teste@hml', "SELECT count(*)::int AS n FROM pg_tables WHERE tablename = 'so_hml'")).toEqual([{ n: 0 }])
    } finally {
      await run(withDb(ADMIN!, CONTROL), 'GRANT DELETE ON migrations TO mcp_control_rw')
    }
  })
})

describe.skipIf(!ADMIN)('control migration 003-target-env sobre dados antigos', () => {
  const db = 'dbmcp_tenv_old'
  const url = () => withDb(ADMIN!, db)
  const migration = readFileSync(path.join(__dirname, '../control-migrations/003-target-env.sql'), 'utf8')
    .split('\n').filter((l) => !l.startsWith('\\')).join('\n')

  beforeAll(async () => {
    await run(ADMIN!, `DROP DATABASE IF EXISTS ${db} WITH (FORCE)`)
    await run(ADMIN!, `CREATE DATABASE ${db}`)
    // Schema antigo: targets com PK só no nome; agents.targets e migrations.target sem @.
    await run(url(), `
      CREATE TABLE agents (client_id text PRIMARY KEY, name text NOT NULL, targets text[] NOT NULL, active boolean NOT NULL DEFAULT true);
      CREATE TABLE targets (name text PRIMARY KEY, env text NOT NULL CHECK (env IN ('hml','prod')),
        dsn_rw_enc text NOT NULL, dsn_exec_enc text NOT NULL, dsn_ddl_enc text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), op_id uuid);
      CREATE TABLE migrations (id bigserial PRIMARY KEY, target text NOT NULL, env text NOT NULL, sql text NOT NULL, checksum text NOT NULL,
        executed_at timestamptz NOT NULL DEFAULT now(), agent_id text NOT NULL, op_id uuid, applied_prod_at timestamptz, applied_prod_op uuid);
      INSERT INTO targets (name, env, dsn_rw_enc, dsn_exec_enc, dsn_ddl_enc) VALUES ('teste_dbmcp', 'hml', 'a', 'b', 'c'), ('loja', 'prod', 'a', 'b', 'c');
      INSERT INTO agents VALUES ('c1', 'a1', ARRAY['teste_dbmcp', 'loja', 'so_env', 'ja@prod'], true);
      INSERT INTO migrations (target, env, sql, checksum, agent_id) VALUES ('teste_dbmcp', 'hml', 'CREATE TABLE x (a int)', 'k', 'c1');`)
  })

  afterAll(async () => {
    if (ADMIN) await run(ADMIN, `DROP DATABASE IF EXISTS ${db} WITH (FORCE)`)
  })

  it('converte agents.targets e migrations.target para nome@env, mantém targets e é idempotente', async () => {
    await run(url(), migration)
    await run(url(), migration)
    expect((await run(url(), 'SELECT targets FROM agents')).rows[0].targets).toEqual(['teste_dbmcp@hml', 'loja@prod', 'so_env', 'ja@prod'])
    expect((await run(url(), 'SELECT name, env FROM targets ORDER BY name')).rows).toEqual([{ name: 'loja', env: 'prod' }, { name: 'teste_dbmcp', env: 'hml' }])
    expect((await run(url(), 'SELECT target FROM migrations')).rows).toEqual([{ target: 'teste_dbmcp@hml' }])
    await run(url(), `INSERT INTO targets (name, env, dsn_rw_enc, dsn_exec_enc, dsn_ddl_enc) VALUES ('teste_dbmcp', 'prod', 'a', 'b', 'c')`)
    await expect(run(url(), `INSERT INTO targets (name, env, dsn_rw_enc, dsn_exec_enc, dsn_ddl_enc) VALUES ('teste_dbmcp', 'prod', 'a', 'b', 'c')`)).rejects.toThrow(/duplicate key/)
  })
})
